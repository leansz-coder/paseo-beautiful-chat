import { ToolCallout } from "../client/components/tool-callouts";
import { PresentationScope } from "../client/presentation-state";
import { toolPresentation, formatToolDuration } from "../client/tool-presentation";
import { buildThemeTokens, type PluginSurfaceColors } from "../client/components/theme-tokens";
import type { ToolCalloutData } from "../shared/contracts";
const tokens = buildThemeTokens({ surface0:"#111111", foreground:"#eeeeee", accent:"#eeeeee", foregroundMuted:"#999999", statusDanger:"#ee5555" } as PluginSurfaceColors);
const data: ToolCalloutData = { id:"test", tool:"bash", title:"npm test", status:"running", command:"npm test", output:"line one\nline two" };
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
const header = (r:ReactTestRenderer) => r.root.findAllByType("Pressable" as any).find(n => n.props.accessibilityState?.expanded !== undefined)!;
it("keeps routine output compact, preserves an explicit expansion across completion and exposes a new failure", async () => {
  let r!:ReactTestRenderer;
  await act(async () => { r=create(<ToolCallout data={data} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(false);
  expect(r.root.findAllByType("Code" as any)).toHaveLength(0);
  await act(async () => { header(r).props.onPress(); });
  await act(async () => { r.update(<ToolCallout data={{...data,status:"completed"}} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(true);
  expect(JSON.stringify(r.toJSON())).toContain("line two");
  await act(async () => { header(r).props.onPress(); });
  await act(async () => { r.update(<ToolCallout data={{...data,status:"failed",output:"real failure"}} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(true);
  expect(JSON.stringify(r.toJSON())).toContain("real failure");
  await act(async () => { r.unmount(); });
});
it("does not apply expansion from another row and automatically reveals unanswered questions", async () => {
  let r!:ReactTestRenderer;
  await act(async () => { r=create(<ToolCallout data={{...data,status:"completed"}} tokens={tokens}/>); });
  await act(async () => { header(r).props.onPress(); });
  await act(async () => { r.update(<ToolCallout data={{...data,id:"other",status:"completed"}} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(false);
  await act(async () => { r.update(<ToolCallout data={{...data,id:"question",tool:"ask",askOptions:[{id:"a",label:"Keep the original"}]}} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(true);
  expect(JSON.stringify(r.toJSON())).toContain("Keep the original");
  await act(async () => { r.unmount(); });
});
it("uses recorded output for bounded previews and does not hide nonzero exit codes", () => {
  expect(toolPresentation({...data,status:"completed",output:"\u001b[32mfirst line\u001b[0m\nsecond line"}).summary).toBe("first line");
  expect(toolPresentation({...data,status:"completed",exitCode:2}).failed).toBe(true);
  expect(toolPresentation({...data,status:"completed",output:"x".repeat(1_000_000)}).summary.length).toBe(161);
  expect(formatToolDuration(12500)).toBe("12.5s");
  expect(formatToolDuration(123000)).toBe("2m 3s");
});
it("keeps the failure reason visible even for typed tools without a text-output body", async () => {
  let r!:ReactTestRenderer;
  await act(async () => { r=create(<ToolCallout data={{...data,tool:"read",status:"failed",filePath:"missing.txt",output:"File not found: missing.txt"}} tokens={tokens}/>); });
  expect(header(r).props.accessibilityState.expanded).toBe(true);
  expect(JSON.stringify(r.toJSON())).toContain("File not found: missing.txt");
  await act(async () => { r.unmount(); });
});
it("restores tool choices after virtual unmount, isolates sessions and reveals a new failure",async()=>{
 let r!:ReactTestRenderer;
 const render=(scope:string,status:ToolCalloutData['status']='completed')=><PresentationScope value={scope}><ToolCallout data={{...data,status}} tokens={tokens}/></PresentationScope>;
 await act(async()=>{r=create(render('host/agent-a/row'));});
 await act(async()=>{header(r).props.onPress();r.unmount();});
 await act(async()=>{r=create(render('host/agent-a/row'));});
 expect(header(r).props.accessibilityState.expanded).toBe(true);
 await act(async()=>{r.update(render('host/agent-b/row'));});
 expect(header(r).props.accessibilityState.expanded).toBe(false);
 await act(async()=>{r.update(render('host/agent-a/row'));header(r).props.onPress();});
 await act(async()=>{r.update(render('host/agent-a/row','failed'));});
 expect(header(r).props.accessibilityState.expanded).toBe(true);
 await act(async()=>{header(r).props.onPress();r.unmount();});
 await act(async()=>{r=create(render('host/agent-a/row','failed'));});
 expect(header(r).props.accessibilityState.expanded).toBe(false);
 await act(async()=>{r.unmount();});
});
