import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { expect, it, vi } from "vitest";
vi.mock("react-native", () => ({ View: "View", Text: "Text", Pressable: "Pressable", StyleSheet: { create: (v: object) => v }, Platform: { OS: "web" } }));
vi.mock("../client/components/glyph", () => ({ Glyph: () => null }));
vi.mock("../client/components/file-type-logo", () => ({ FileTypeLogo: () => null }));
vi.mock("../client/components/motion", () => ({ Rotate: ({ children }: any) => children }));
vi.mock("../client/components/pulse-dot", () => ({ PulseDot: () => null }));
